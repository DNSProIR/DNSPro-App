package main

import (
	"fmt"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// context helpers live in context_util.go

type Backend string

const (
	BackendNetworkManager Backend = "networkmanager"
	BackendResolved       Backend = "systemd-resolved"
	BackendResolvConf     Backend = "resolv.conf"
)

func DetectBackend() Backend {
	if commandExists("nmcli") && nmActive() {
		return BackendNetworkManager
	}
	if commandExists("resolvectl") && resolvedActive() {
		return BackendResolved
	}
	return BackendResolvConf
}

func IsActive(cfg Config) bool {
	addrs, err := currentDNS()
	if err != nil {
		return false
	}
	want := cfg.PrimaryIPv4
	for _, a := range addrs {
		if a == want {
			return true
		}
	}
	return false
}

func Enable(cfg Config) error {
	return withPrivilege(func() error {
		switch DetectBackend() {
		case BackendNetworkManager:
			return enableNM(cfg)
		case BackendResolved:
			return enableResolved(cfg)
		default:
			return enableResolvConf(cfg)
		}
	})
}

func Disable(cfg Config) error {
	return withPrivilege(func() error {
		switch DetectBackend() {
		case BackendNetworkManager:
			return disableNM()
		case BackendResolved:
			return disableResolved()
		default:
			return disableResolvConf()
		}
	})
}

func CheckConnection(cfg Config) error {
	d := net.Dialer{Timeout: 5 * time.Second}
	conn, err := d.Dial("udp", net.JoinHostPort(cfg.PrimaryIPv4, "53"))
	if err == nil {
		_ = conn.Close()
	}
	resolver := &net.Resolver{PreferGo: true}
	ctx, cancel := contextWithTimeout(8 * time.Second)
	defer cancel()
	_, err = resolver.LookupHost(ctx, cfg.CheckHost)
	return err
}

func withPrivilege(fn func() error) error {
	if os.Geteuid() != 0 {
		return fmt.Errorf("root privileges required (use pkexec or run: dnspro enable / dnspro disable)")
	}
	return fn()
}

func elevateAndRun(args ...string) error {
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	cmd := exec.Command("pkexec", append([]string{exe}, args...)...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func EnableElevated(cfg Config) error {
	if os.Geteuid() == 0 {
		return Enable(cfg)
	}
	return elevateAndRun("enable", "--apply")
}

func DisableElevated(cfg Config) error {
	if os.Geteuid() == 0 {
		return Disable(cfg)
	}
	return elevateAndRun("disable", "--apply")
}

func enableNM(cfg Config) error {
	conn, err := activeNMConnection()
	if err != nil {
		return err
	}
	servers := strings.Join(cfg.Servers(), " ")
	if err := run("nmcli", "connection", "modify", conn, "ipv4.ignore-auto-dns", "yes"); err != nil {
		return err
	}
	if err := run("nmcli", "connection", "modify", conn, "ipv4.dns", servers); err != nil {
		return err
	}
	return run("nmcli", "connection", "up", conn)
}

func disableNM() error {
	conn, err := activeNMConnection()
	if err != nil {
		return err
	}
	_ = run("nmcli", "connection", "modify", conn, "ipv4.dns", "")
	if err := run("nmcli", "connection", "modify", conn, "ipv4.ignore-auto-dns", "no"); err != nil {
		return err
	}
	return run("nmcli", "connection", "up", conn)
}

func enableResolved(cfg Config) error {
	iface, err := defaultInterface()
	if err != nil {
		return err
	}
	args := append([]string{"dns", iface}, cfg.Servers()...)
	return run("resolvectl", args...)
}

func disableResolved() error {
	iface, err := defaultInterface()
	if err != nil {
		return err
	}
	return run("resolvectl", "revert", iface)
}

func enableResolvConf(cfg Config) error {
	const path = "/etc/resolv.conf"
	backup := filepath.Join(os.TempDir(), "dnspro-resolv.conf.bak")
	if data, err := os.ReadFile(path); err == nil {
		_ = os.WriteFile(backup, data, 0644)
		stateDir := "/var/lib/dnspro"
		_ = os.MkdirAll(stateDir, 0755)
		_ = os.WriteFile(filepath.Join(stateDir, "resolv.conf.bak"), data, 0644)
	}
	var b strings.Builder
	b.WriteString("# Generated by DNSPro\n")
	for _, s := range cfg.Servers() {
		b.WriteString("nameserver ")
		b.WriteString(s)
		b.WriteString("\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0644)
}

func disableResolvConf() error {
	const path = "/etc/resolv.conf"
	bak := "/var/lib/dnspro/resolv.conf.bak"
	data, err := os.ReadFile(bak)
	if err != nil {
		return fmt.Errorf("no resolv.conf backup found; restore DNS manually")
	}
	return os.WriteFile(path, data, 0644)
}

func activeNMConnection() (string, error) {
	out, err := exec.Command("nmcli", "-t", "-f", "NAME,DEVICE", "connection", "show", "--active").Output()
	if err != nil {
		return "", err
	}
	lines := strings.Split(strings.TrimSpace(string(out)), "\n")
	for _, line := range lines {
		parts := strings.SplitN(line, ":", 2)
		if len(parts) == 0 || parts[0] == "" {
			continue
		}
		if len(parts) > 1 && (parts[1] == "lo" || parts[1] == "") {
			continue
		}
		return parts[0], nil
	}
	return "", fmt.Errorf("no active NetworkManager connection")
}

func defaultInterface() (string, error) {
	out, err := exec.Command("sh", "-c", "ip -4 route show default | awk '{print $5; exit}'").Output()
	if err != nil {
		return "", err
	}
	iface := strings.TrimSpace(string(out))
	if iface == "" {
		return "", fmt.Errorf("could not detect default network interface")
	}
	return iface, nil
}

func currentDNS() ([]string, error) {
	data, err := os.ReadFile("/etc/resolv.conf")
	if err != nil {
		return nil, err
	}
	var servers []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "nameserver ") {
			servers = append(servers, strings.Fields(line)[1])
		}
	}
	return servers, nil
}

func nmActive() bool {
	out, err := exec.Command("nmcli", "general", "status").Output()
	if err != nil {
		return false
	}
	return strings.Contains(string(out), "connected") || strings.Contains(strings.ToLower(string(out)), "asleep") || len(out) > 0
}

func resolvedActive() bool {
	return run("systemctl", "is-active", "--quiet", "systemd-resolved") == nil
}

func commandExists(name string) bool {
	_, err := exec.LookPath(name)
	return err == nil
}

func run(name string, args ...string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func StatusLine(cfg Config) string {
	active := IsActive(cfg)
	backend := DetectBackend()
	state := "Inactive"
	if active {
		state = "Active"
	}
	return fmt.Sprintf("Status: %s (backend: %s, dns: %s)", state, backend, cfg.PrimaryIPv4)
}
